        <h2>Cobertura</h2>
        <p>
            La disponibilidad del servicio depende del código postal de origen, código postal de destino,
            paquetería seleccionada, tipo de paquete, peso, dimensiones y cobertura operativa vigente.
        </p>

        <h2>Tiempos de entrega</h2>
        <p>
            Los tiempos mostrados son estimados y pueden variar por zona extendida, alta demanda,
            clima, incidencias operativas, días inhábiles, validaciones internas o causas ajenas a ZIGO.
        </p>

        <h2>Empaque</h2>
        <p>
            El usuario es responsable de entregar el paquete correctamente cerrado, protegido y etiquetado.
            El empaque debe ser adecuado al peso, valor, fragilidad y características del contenido.
        </p>

        <h2>Artículos no permitidos</h2>
        <p>
            No se aceptan artículos prohibidos por ley, materiales peligrosos, sustancias ilegales,
            armas, dinero en efectivo, documentos negociables, animales vivos, productos perecederos
            sin manejo autorizado, mercancía de procedencia ilícita o cualquier contenido restringido
            por la paquetería.
        </p>

        <h2>Peso y dimensiones</h2>
        <p>
            Si la paquetería detecta diferencias entre los datos declarados y las medidas reales del
            paquete, podrán generarse cargos adicionales, ajustes de tarifa, retención, devolución
            o cancelación del servicio.
        </p>

        <h2>Recolección y entrega</h2>
        <p>
            La recolección y entrega dependen de la operación de la paquetería seleccionada. El usuario
            debe asegurar que exista una persona disponible en domicilio y que los datos sean correctos.
        </p>

        <h2>Rastreo</h2>
        <p>
            El rastreo se realiza con el número de guía generado. La actualización de eventos depende
            de los sistemas de la paquetería y puede no reflejarse en tiempo real.
        </p>

        <h2>Incidencias</h2>
        <p>
            Cualquier aclaración por pérdida, daño, retraso, devolución o entrega no reconocida deberá
            reportarse con evidencia suficiente: guía, comprobante, fotografías, descripción del contenido
            y datos del envío.
        </p>
